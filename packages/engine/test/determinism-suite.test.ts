/**
 * The determinism suite (plan §1 item 8, §8 "Controles negativos"): tally passes every check, on
 * the golden run and on generated commands; each deliberately broken ruleset fails exactly the
 * property that must catch it, at the tick it diverges; and the comparison is made tick by tick.
 *
 * Time: the golden subject runs about 13,000 ticks in process, one run under audit, and three
 * child processes, about 5.3 s on the 2-core Codespace (Bun 1.4.4, 2026-10-25). The tests are
 * asynchronous, but each run is synchronous between its awaits, so a timeout is a budget, as in
 * step-fuzz.test.ts: 60 s allows about eleven times it.
 */

const TALLY = { module: import.meta.resolve("./fixtures/tally-ruleset.ts"), name: "tallyRuleset" };
const GOLDEN_SEED: Seed = [GOLDEN_TALLY.seed[0], GOLDEN_TALLY.seed[1]];
const GOLDEN_CUTS = [0, 1, 2, 37, 299, 300, 999];
const GOLDEN_CHILD_CUTS = [0, 37, 999];

/** The golden tally run, with the cuts the snapshot resumption has always used. */
const GOLDEN_SUBJECT: DeterminismSubject = {
  ruleset: TALLY,
  world: (seed, ruleset, audit) => tallyWorld(seed, audit, ruleset),
  seeds: [GOLDEN_SEED, [3, 4]],
  ticks: GOLDEN_TALLY.ticks,
  commands: tallyCommands,
  cuts: GOLDEN_CUTS,
  childCuts: GOLDEN_CHILD_CUTS,
};

describe("positive control: tally passes every check", () => {
  test("over the golden run, with the golden checksums and final state root", async () => {
    const report = await runDeterminismSuite(GOLDEN_SUBJECT);
    expect(report.failures).toEqual([]);
    expect(report.resumed).toEqual(GOLDEN_CUTS);
    expect(report.childResumed).toEqual(GOLDEN_CHILD_CUTS);
    expect(report.reference).toHaveLength(GOLDEN_TALLY.ticks);
    expect(report.reference.at(-1)).toMatchObject({ checksum: GOLDEN_TALLY.checksums[1000] });
    const final = JSON.parse(report.finalText ?? "{}") as { stateRoot?: string };
    expect(final.stateRoot).toBe(GOLDEN_TALLY.stateRoot);
  }, 60_000);

  test("over 200 ticks of commands generated by sfc32", async () => {
    const random = new Sfc32(41);
    const report = await runDeterminismSuite({
      ...GOLDEN_SUBJECT,
      seeds: [
        [41, 288],
        [7, 9],
      ],
      ticks: 200,
      commands: (tick) => validCommands(random, tick),
      cuts: [0, 50, 199],
      childCuts: [100],
    });
    expect(report.failures).toEqual([]);
    expect([report.resumed, report.childResumed]).toEqual([[0, 50, 199], [100]]);
  }, 60_000);
});

