describe("negative controls: the suite reports each broken ruleset", () => {
  test.each(CONTROLS)(
    "%s",
    async (name, cuts, childCuts, failures) => {
      const report = await runDeterminismSuite(controlSubject(name, cuts, childCuts));
      expect(report.failures).toEqual(failures);
    },
    60_000,
  );
});

describe("a child process that does not resume", () => {
  /** The failures of the suite on the control `name` with one child cut, at 4. */
  const childFailures = async (name: string, childTimeoutMs?: number) => {
    const report = await runDeterminismSuite(controlSubject(name, [0], [4]), { childTimeoutMs });
    return report.failures;
  };
  /**
   * The failures of a ruleset that fails in every child process: the resume from 4, and the run
   * of the second seed alone, which the interleaving compares with, from 0.
   */
  const failure = (resume: string, second = resume): Failure[] => [
    { property: "child-resume", tick: 4, at: 4, detail: resume },
    { property: "interleave", tick: 0, at: 1, detail: second },
  ];

  test("that exits with an error is a child-resume failure with the end of its stderr", async () => {
    expect(await childFailures("exitsInChild")).toEqual(
      failure("the child process exited with 3: the child failed on purpose"),
    );
  }, 60_000);

  test("that runs past its time limit is killed, reaped, and reported", async () => {
    const failures = await childFailures("hangsInChild", 1_000);
    // Each child writes its process id to stderr before it hangs.
    const pids = failures.map(({ detail }) => Number(/child (\d+) hangs$/.exec(detail)?.[1]));
    const killed = (pid?: number) =>
      `the child process ran past 1000 ms and was killed with SIGKILL: child ${pid} hangs`;
    expect(failures).toEqual(failure(killed(pids[0]), killed(pids[1])));
    // Signal 0 only checks that a process exists: each was killed and reaped, so none is left.
    for (const pid of pids) expect(() => process.kill(pid, 0)).toThrow("ESRCH");
  }, 60_000);

  test("that still runs when an in-process check throws is killed before the error propagates", async () => {
    /** The processes this process started that run resume-child.ts, as `ps` lists them. */
    const resumeChildren = () =>
      Bun.spawnSync(["ps", "-A", "-o", "pid=,ppid=,command="])
        .stdout.toString()
        .split("\n")
        .filter((line) => {
          const ppid = Number(line.trim().split(/\s+/)[1]);
          return ppid === process.pid && line.includes("resume-child.ts");
        });
    const subject = controlSubject("hangsInChild", [], [4]);
    let running: string[] = [];
    let secondWorlds = 0;
    const failing: DeterminismSubject = {
      ...subject,
      // The first world with the second seed is built before any child starts, for the run of
      // that seed alone; the next one, the interleaving's, while both children run.
      world: (seed, ruleset, audit) => {
        if (seed !== subject.seeds[1] || secondWorlds++ === 0) {
          return subject.world(seed, ruleset, audit);
        }
        running = resumeChildren();
        throw new Error("no world for the second seed");
      },
    };
    await expect(runDeterminismSuite(failing)).rejects.toThrow("no world for the second seed");
    expect(running).toHaveLength(2);
    expect(resumeChildren()).toEqual([]);
  }, 60_000);

  test("whose world cannot be encoded is an interleave failure, and the first seed's worlds are still compared", async () => {
    const subject = controlSubject("keepsLastTick", [0]);
    let secondWorlds = 0;
    const report = await runDeterminismSuite({
      ...subject,
      // The first world with the second seed, built for its run alone, runs a ruleset that writes
      // behind the barrier, stepped past that write, so its snapshot cannot be encoded. The
      // interleaving's worlds run keepsLastTick, which only the interleaving catches.
      world: (seed, ruleset, audit) => {
        if (seed !== subject.seeds[1] || secondWorlds++ > 0) {
          return subject.world(seed, ruleset, audit);
        }
        const world = subject.world(seed, writesThroughReadChunk(), false);
        for (let tick = 1; tick <= BYPASS_TICK; tick += 1) step(world, []);
        return world;
      },
    });
    expect(report.failures).toEqual([
      { property: "interleave", tick: 2, at: 0, detail: "checksum, stats differ" },
      {
        property: "interleave",
        tick: 0,
        at: 1,
        detail: `encodeSnapshot of the second seed's world threw ${STALE}`,
      },
      { property: "interleave", tick: 1, at: 2, detail: "checksum differs" },
    ]);
  }, 60_000);

  test.each([
    ["nothing", "writesNothingInChild", "the child process exited with 0 and wrote nothing"],
    [
      "text that is not JSON",
      "writesTextInChild",
      "the child process wrote output that is not JSON: not JSON",
    ],
    [
      "JSON of another shape",
      "writesOtherJsonInChild",
      'the child process wrote JSON that is not a ChildOutput: {"records":[{"tick":"1"}]}',
    ],
  ])(
    "that exits with 0 but writes %s is a child-resume failure",
    async (_what, name, detail) => {
      expect(await childFailures(name)).toEqual(failure(detail));
    },
    60_000,
  );
});

describe("the comparison", () => {
  const record = (tick: number, checksum: string): TickRecord => ({
    tick,
    checksum,
    events: "[]",
    changedChunks: "[]",
    stats: "{}",
  });

  test("is made at every tick: a divergence that heals is still found, at its tick", () => {
    const expected = [record(1, "a"), record(2, "b"), record(3, "c")];
    const healed = [record(1, "a"), record(2, "x"), record(3, "c")];
    expect(firstDivergence(expected, healed)).toEqual({ tick: 2, detail: "checksum differs" });
    expect(firstDivergence(expected, expected)).toBeUndefined();
  });

  test("finds a run that stopped early, and one that ran on", () => {
    const expected = [record(1, "a"), record(2, "b")];
    expect(firstDivergence(expected, expected.slice(0, 1))).toEqual({
      tick: 2,
      detail: "the run has no tick",
    });
    expect(firstDivergence(expected.slice(0, 1), expected)).toEqual({
      tick: 2,
      detail: "the run has an extra tick",
    });
  });
});

describe("a subject the suite cannot run is refused before anything runs", () => {
  test("cuts outside the run, and ticks that are not positive, all at once", async () => {
    const subject = { ...controlSubject("sharesCounter", [12, -1], [0.5]), ticks: 12 };
    await expect(runDeterminismSuite(subject)).rejects.toThrow(
      "invalid determinism subject: the cut 12 is not a tick in [0, 12); the cut -1 is not a tick in [0, 12); the cut 0.5 is not a tick in [0, 12)",
    );
    await expect(
      runDeterminismSuite({ ...subject, ticks: 0, cuts: [], childCuts: [] }),
    ).rejects.toThrow("ticks 0 is not positive");
  });

  test("a subject with no cut, in process or in a child", async () => {
    const subject = controlSubject("sharesCounter", [], []);
    await expect(runDeterminismSuite(subject)).rejects.toThrow(
      "invalid determinism subject: the subject has no cut: list a tick in cuts or childCuts",
    );
  });

  test("a child time limit that is not a positive integer", async () => {
    const subject = controlSubject("sharesCounter", [0]);
    for (const childTimeoutMs of [0, -1, 1.5, Number.NaN]) {
      await expect(runDeterminismSuite(subject, { childTimeoutMs })).rejects.toThrow(
        `invalid determinism options: childTimeoutMs ${childTimeoutMs} is not a positive integer`,
      );
    }
  });

  test("a ruleset module that does not export the factory", async () => {
    const subject = { ...GOLDEN_SUBJECT, ruleset: { ...TALLY, name: "noSuchRuleset" } };
    await expect(runDeterminismSuite(subject)).rejects.toThrow("exports no function noSuchRuleset");
  });
});
